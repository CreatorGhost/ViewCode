// Embeds apps/server/src/diagrams/stack-diagram in the server bundle, so the skill reaches the
// agent's disk from dev, dist, the desktop app and the single executable alike.
// Run after changing any file there: node scripts/generate-stack-diagram-skill.ts
// @effect-diagnostics nodeBuiltinImport:off globalConsole:off - a build-time script, no Effect runtime.
import * as NodeCrypto from "node:crypto";
import * as NodeFS from "node:fs";
import * as NodePath from "node:path";

const root = NodePath.join(import.meta.dirname, "..");
const skillDir = NodePath.join(root, "apps/server/src/diagrams/stack-diagram");
const output = NodePath.join(root, "apps/server/src/diagrams/stackDiagramSkill.generated.ts");

export function readSkillFiles(): Array<{ path: string; base64: string }> {
  return NodeFS.readdirSync(skillDir, { recursive: true, encoding: "utf8" })
    .filter((path) => NodeFS.statSync(NodePath.join(skillDir, path)).isFile())
    .map((path) => path.split(NodePath.sep).join("/"))
    .toSorted()
    .map((path) => ({
      path,
      base64: NodeFS.readFileSync(NodePath.join(skillDir, path)).toString("base64"),
    }));
}

export function renderGeneratedModule(files: ReadonlyArray<{ path: string; base64: string }>) {
  const version = NodeCrypto.createHash("sha256")
    .update(files.map((file) => `${file.path}\0${file.base64}`).join("\n"))
    .digest("hex")
    .slice(0, 16);
  return `// Generated by scripts/generate-stack-diagram-skill.ts from apps/server/src/diagrams/stack-diagram. Do not edit.
export const STACK_DIAGRAM_SKILL_VERSION = "${version}";

export const STACK_DIAGRAM_SKILL_FILES: ReadonlyArray<{
  readonly path: string;
  readonly base64: string;
}> = ${JSON.stringify(files, null, 2)};
`;
}

if (import.meta.main) {
  NodeFS.writeFileSync(output, renderGeneratedModule(readSkillFiles()));
  console.log(`wrote ${NodePath.relative(root, output)}`);
}
