import { describe, expect, it } from "@effect/vitest";

import {
  LEARNED_REVIEW_STYLE_MAX_SAMPLE_CHARS,
  LEARNED_REVIEW_STYLE_MAX_SAMPLES,
  parseLearnedReviewStyleAnswer,
  selectLearnedReviewStyleSamples,
  type LearnedReviewStyleCandidate,
} from "./learnedReviewStyleSamples.ts";

const answer = {
  data: {
    viewer: {
      login: "Bilal",
      contributionsCollection: {
        pullRequestReviewContributions: {
          nodes: [
            {
              pullRequestReview: {
                body: "Two small things, otherwise good to go.",
                state: "APPROVED",
                createdAt: "2026-09-02T10:00:00Z",
                comments: {
                  nodes: [
                    { body: "nit: `cfg` -> `config`?", createdAt: "2026-09-02T09:58:00Z" },
                    null,
                  ],
                },
              },
            },
            // A repository the token cannot see, and a review nobody has read yet.
            null,
            {
              pullRequestReview: {
                body: "",
                state: "PENDING",
                createdAt: "2026-09-03T00:00:00Z",
                comments: { nodes: [{ body: "draft", createdAt: "2026-09-03T00:00:00Z" }] },
              },
            },
            {
              pullRequestReview: {
                body: "",
                state: "CHANGES_REQUESTED",
                createdAt: "2026-08-01T00:00:00Z",
                comments: {
                  nodes: [
                    {
                      body: "This drops the error. Can we bubble it up?",
                      createdAt: "2026-08-01T00:00:00Z",
                    },
                  ],
                },
              },
            },
          ],
        },
      },
    },
  },
};

const candidate = (
  text: string,
  createdAt = "2026-09-01T00:00:00Z",
): LearnedReviewStyleCandidate => ({ kind: "inline", state: "commented", text, createdAt });

describe("parseLearnedReviewStyleAnswer", () => {
  it("reads every submitted review's text and line comments with the review's state", () => {
    const parsed = parseLearnedReviewStyleAnswer(JSON.stringify(answer));
    expect(parsed?.login).toBe("Bilal");
    expect(parsed?.candidates).toEqual([
      {
        kind: "summary",
        state: "approved",
        text: "Two small things, otherwise good to go.",
        createdAt: "2026-09-02T10:00:00Z",
      },
      {
        kind: "inline",
        state: "approved",
        text: "nit: `cfg` -> `config`?",
        createdAt: "2026-09-02T09:58:00Z",
      },
      { kind: "summary", state: "changes-requested", text: "", createdAt: "2026-08-01T00:00:00Z" },
      {
        kind: "inline",
        state: "changes-requested",
        text: "This drops the error. Can we bubble it up?",
        createdAt: "2026-08-01T00:00:00Z",
      },
    ]);
  });

  it("refuses an answer that is not one", () => {
    expect(parseLearnedReviewStyleAnswer('{"errors":[{"message":"Bad credentials"}]}')).toBeNull();
    expect(parseLearnedReviewStyleAnswer("not json")).toBeNull();
  });
});

describe("selectLearnedReviewStyleSamples", () => {
  it("keeps the user's own words, newest first, without approvals, bots or repeats", () => {
    const samples = selectLearnedReviewStyleSamples([
      candidate("Older but real: why a Map here?", "2026-01-01T00:00:00Z"),
      candidate("   "),
      candidate("LGTM!"),
      candidate("lgtm 🚀"),
      candidate("Looks good to me."),
      candidate("+1"),
      candidate("👍"),
      candidate("/retest"),
      candidate("@dependabot rebase"),
      candidate("<!-- review-bot --> Summary of changes"),
      candidate("Generated by an assistant: three issues found."),
      candidate("nit: typo", "2026-09-05T00:00:00Z"),
      candidate("nit: typo", "2026-09-04T00:00:00Z"),
      candidate("Blocking: this leaks the token\r\ninto the log.", "2026-09-06T00:00:00Z"),
    ]);
    expect(samples.map((sample) => sample.text)).toEqual([
      "Blocking: this leaks the token\ninto the log.",
      "nit: typo",
      "Older but real: why a Map here?",
    ]);
  });

  it("cuts long text at a word and keeps only the newest samples", () => {
    const long = `${"word ".repeat(600)}end`;
    const [sample] = selectLearnedReviewStyleSamples([candidate(long)]);
    expect(sample?.text.length).toBeLessThanOrEqual(LEARNED_REVIEW_STYLE_MAX_SAMPLE_CHARS);
    expect(sample?.text).toMatch(/word…$/);

    const many = Array.from({ length: 60 }, (_, index) =>
      candidate(`Comment number ${index}`, `2026-01-01T00:${String(index).padStart(2, "0")}:00Z`),
    );
    const kept = selectLearnedReviewStyleSamples(many);
    expect(kept).toHaveLength(LEARNED_REVIEW_STYLE_MAX_SAMPLES);
    expect(kept[0]?.text).toBe("Comment number 59");
  });
});
